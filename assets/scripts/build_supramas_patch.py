def read_persona(path: Path) -> str:
    """Return the contract body with its YAML frontmatter removed."""
    text = path.read_text(encoding="utf-8")
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4 :]
    return text.strip("\n")


def indent_block(text: str, spaces: int) -> str:
    pad = " " * spaces
    return "\n".join((pad + line) if line.strip() else "" for line in text.splitlines())


def render_role(stem: str, spec: dict, indent: int = 4) -> str:
    """Render one `dsh-tool-subagent` row at the given dash indent."""
    persona_path = AGENTS_DIR / f"{stem}.md"
    if not persona_path.is_file():
        raise SystemExit(f"missing role contract: {persona_path}")
    persona = read_persona(persona_path)

    key = " " * (indent + 2)
    value = " " * (indent + 4)
    lines = [
        f"{' ' * indent}- id: tool-subagent-{spec['tool_name']}",
        f"{key}name: '{TOOL_SUBAGENT}'",
        f"{key}config:",
        f"{value}provider: spawn",
        f"{value}toolName: {spec['tool_name']}",
    ]
    for config_key, config_value in spec["extra"].items():
        if isinstance(config_value, dict):
            lines.append(f"{value}{config_key}:")
            for sub_key, sub_value in config_value.items():
                rendered = "[" + ", ".join(f"'{item}'" for item in sub_value) + "]"
                lines.append(f"{value}  {sub_key}: {rendered}")
        else:
            lines.append(f"{value}{config_key}: {config_value}")
    lines.append(f"{value}persona: |")
    lines.append(indent_block(persona, indent + 6))
    return "\n".join(lines) + "\n"


def ordered_roles() -> list[tuple[str, dict]]:
    """Strategy roles first so the generated file reads in pipeline order."""
    stems = list(ROLES)
    stems.sort(key=lambda stem: (not stem.startswith("strategy-"), list(ROLES).index(stem)))
    return [(stem, ROLES[stem]) for stem in stems]


def build_global_patch() -> str:
    parts = [GLOBAL_HEADER, "- insert:\n"]
    for stem, spec in ordered_roles():
        parts.append(render_role(stem, spec, indent=4))
    return "\n".join(parts)


def build_preset_patch() -> str:
    roles = "\n".join(render_role(stem, spec, indent=14) for stem, spec in ordered_roles())
    # Deliberately not str.format(): the roster carries DSH template placeholders
    # such as {{cwd}}, and format() would collapse them to {cwd}.
    roster = PRESET_ROSTER.replace(
        "@@PERSONA@@", indent_block(PERSONA.strip("\n"), 16)
    ).replace("@@ROLES@@", roles)
    return "\n".join(
        [
            PRESET_HEADER,
            "- insert:",
            "    - id: preset-materials-research",
            "      name: '@deepseek-ai/dsh-agent-preset'",
            "      config:",
            f"        id: {PRESET_ID}",
            f"        name: {PRESET_NAME}",
            "        description: 面向材料科学的文献策略树挖掘与证据可追溯的 idea 设计（REBCO 磁通钉扎）。",
            "        order: 10",
            "        plugins:",
            roster.rstrip("\n"),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify instead of writing.")
    args = parser.parse_args()

    if not AGENTS_DIR.is_dir():
        print(f"agents directory not found: {AGENTS_DIR}", file=sys.stderr)
        return 1

    generated = {
        PATCH_PATH: build_global_patch(),
        PRESET_PATH: build_preset_patch(),
    }

    if args.check:
        stale = [
            str(path)
            for path, content in generated.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print("out of date:\n  " + "\n  ".join(stale), file=sys.stderr)
            return 1
        print(f"up to date: {len(generated)} patches, {len(ROLES)} roles")
        return 0

    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
