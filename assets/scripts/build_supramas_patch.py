#!/usr/bin/env python3
"""Generate the SupraMAS DSH bundle patches from the role-contract Markdown files.

`packages/supramas-dsh/agents/*.md` are the single source of truth for role
contracts. Two patch files are generated from them, because the two consumers
select their toolset differently:

* `cordis.patch.yml` — profile-level rows. This is what `dsh --profile headless
  --patch ...` loads, and the headless profile has no preset registry, so the
  delegation roles have to be global there.
* `presets/materials-research.patch.yml` — one `@deepseek-ai/dsh-agent-preset`
  declaration. A preset declares the *complete* toolset for its sessions, so this
  file also carries the standard research roster (bash/fs/skills/web/...), a
  materials-research persona, and the same delegation roles.

Contracts are inlined as YAML literal blocks rather than read through `!!js`
expressions: inlining keeps each patch self-contained, independent of the process
working directory, and verifiable without booting an agent.

Usage:
    PYTHONDONTWRITEBYTECODE=1 python3 scripts/build_supramas_patch.py          # write
    PYTHONDONTWRITEBYTECODE=1 python3 scripts/build_supramas_patch.py --check  # verify
"""

